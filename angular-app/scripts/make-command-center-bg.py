"""Usage: python scripts/make-command-center-bg.py src/assets/command-center-bg.svg

Vector recreation of assets/komoditas-card-bg.png for the Command Center background.

Same composition as the PNG (a diagonal gradient plus a curved grid of tilted tiles, faint and
sparse on the left, denser and brighter on the right), but every colour is a design-system token
(biru / teal ramps from styles/_tokens.scss) instead of the PNG's own royal blue.
Deterministic: same seed, same output.
"""
import math
import random
import sys

W, H = 1372, 537
rnd = random.Random(20261023)

# design-system ramps
BIRU_950, BIRU_900, BIRU_800, BIRU_700, BIRU_600, BIRU_500 = '#050f19', '#081826', '#0c2233', '#102c40', '#163b54', '#2a5a78'
TEAL_700, TEAL_600, TEAL_500, TEAL_400 = '#286a82', '#33809c', '#14a5c0', '#4b95ad'

tiles = []
cols, rows = 15, 12
for c in range(cols):
    u = c / (cols - 1)                      # 0 left .. 1 right
    for r in range(-2, rows):
        v = r / (rows - 1)
        # curved grid: columns lean right, rows bend upward toward the right edge
        x = 90 + u * (W - 40) + v * 40 * u
        y = 20 + v * (H + 40) - (u ** 2) * 150 + math.sin(u * math.pi) * 20
        if y < -60 or y > H + 30:
            continue
        # density and brightness rise toward the right
        if rnd.random() > 0.35 + 0.6 * u:
            continue
        w = (70 + 25 * u) * (0.8 + rnd.random() * 0.4)
        h = (12 + 16 * u ** 1.5) * (0.7 + rnd.random() * 0.8)
        angle = 10 + 12 * u                 # clockwise tilt, steeper on the right
        bright = u ** 2 * rnd.random()
        if bright > 0.55:
            fill, op = TEAL_500, 0.55 + 0.3 * rnd.random()
        elif bright > 0.3:
            fill, op = TEAL_600, 0.45 + 0.25 * rnd.random()
        elif u > 0.55:
            fill, op = BIRU_500, 0.35 + 0.25 * rnd.random()
        else:
            fill, op = BIRU_500, 0.12 + 0.18 * rnd.random()
        tiles.append(
            f'<rect x="{x - w / 2:.1f}" y="{y - h / 2:.1f}" width="{w:.1f}" height="{h:.1f}" '
            f'fill="{fill}" opacity="{op:.2f}" transform="rotate({angle:.1f} {x:.1f} {y:.1f})"/>'
        )

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMid slice">
  <!-- Vector recreation of komoditas-card-bg.png in design-system colours (biru/teal ramps). Generated by angular-app/scripts/make-command-center-bg.py. -->
  <defs>
    <linearGradient id="g" x1="0" y1="0" x2="0.35" y2="1">
      <stop offset="0" stop-color="{BIRU_600}"/>
      <stop offset="0.45" stop-color="{BIRU_800}"/>
      <stop offset="1" stop-color="{BIRU_950}"/>
    </linearGradient>
    <radialGradient id="glow" cx="0.88" cy="0.35" r="0.55">
      <stop offset="0" stop-color="{TEAL_700}" stop-opacity="0.35"/>
      <stop offset="1" stop-color="{TEAL_700}" stop-opacity="0"/>
    </radialGradient>
  </defs>
  <rect width="{W}" height="{H}" fill="url(#g)"/>
  <rect width="{W}" height="{H}" fill="url(#glow)"/>
  <g>
    {chr(10).join('    ' + t for t in tiles).lstrip()}
  </g>
</svg>
'''
open(sys.argv[1], 'w', encoding='utf-8').write(svg)
print(len(tiles), 'tiles')
